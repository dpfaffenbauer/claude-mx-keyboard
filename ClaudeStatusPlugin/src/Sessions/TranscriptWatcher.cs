namespace Loupedeck.ClaudeStatusPlugin
{
    using System;
    using System.Buffers;
    using System.IO;
    using System.Text.Json;

    public enum TurnState
    {
        Unknown,
        Open,         // Claude is mid-turn (prompt, tool call or tool result is the last entry)
        Ended,        // end_turn / turn_duration / stop hook
        Interrupted,  // "[Request interrupted by user]" – Esc fires no Stop hook
        Command,      // a local slash command (/rename, /status, ...) – nothing to look at
    }

    // Follows a session transcript (*.jsonl):
    // - its current name:
    //     {"type":"custom-title","customTitle":"..."}   set via /rename  (wins)
    //     {"type":"ai-title","aiTitle":"..."}           generated by Claude Code
    //   Transcripts grow to 100+ MB, so the file is scanned once and afterwards
    //   only the appended bytes are read.
    // - whether the last turn is still running, from the entries at the end of the file.
    public sealed class TranscriptWatcher
    {
        private const Int32 ChunkSize = 1 << 20;
        private const Int32 MaxTitleLine = 8192;
        private const Int32 TurnTailBytes = 512 * 1024;
        private const Int32 MaxParsedLine = 256 * 1024;

        private static readonly Byte[] CustomMarker = "{\"type\":\"custom-title\""u8.ToArray();
        private static readonly Byte[] AiMarker = "{\"type\":\"ai-title\""u8.ToArray();
        private static readonly Byte[] NlCustomMarker = "\n{\"type\":\"custom-title\""u8.ToArray();
        private static readonly Byte[] NlAiMarker = "\n{\"type\":\"ai-title\""u8.ToArray();
        private static readonly Int32 Overlap = Math.Max(NlCustomMarker.Length, NlAiMarker.Length) - 1;

        private Int64 _scanned;
        private Int64 _lastLength = -1;
        private String _customTitle;
        private String _aiTitle;

        public TranscriptWatcher(String path) => this.Path = path;

        public String Path { get; }

        public String Title => this._customTitle ?? this._aiTitle;

        public TurnState Turn { get; private set; }

        // unix seconds of the last transcript write
        public Int64 LastWrite { get; private set; }

        public void Update()
        {
            Int64 length;
            try
            {
                var info = new FileInfo(this.Path);
                length = info.Length;
                this.LastWrite = new DateTimeOffset(info.LastWriteTimeUtc).ToUnixTimeSeconds();
            }
            catch (IOException)
            {
                return;
            }

            if (length == this._lastLength)
            {
                return;
            }

            if (length < this._scanned)
            {
                // rewritten: start over
                this._scanned = 0;
                this._customTitle = this._aiTitle = null;
            }

            this._lastLength = length;
            try
            {
                using var handle = File.OpenHandle(this.Path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete);
                this.Scan(handle, length);
                this.Turn = ReadTurn(handle, length);
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                this._lastLength = -1;
            }
        }

        private void Scan(Microsoft.Win32.SafeHandles.SafeFileHandle handle, Int64 length)
        {
            var buffer = ArrayPool<Byte>.Shared.Rent(ChunkSize);
            try
            {
                var pos = this._scanned;
                if (pos == 0 && !this.TryHandleLineAt(handle, 0, length, out _))
                {
                    return;
                }

                while (pos < length)
                {
                    var read = RandomAccess.Read(handle, buffer.AsSpan(0, (Int32)Math.Min(ChunkSize, length - pos)), pos);
                    if (read <= 0)
                    {
                        break;
                    }

                    var chunk = buffer.AsSpan(0, read);
                    foreach (var marker in new[] { NlCustomMarker, NlAiMarker })
                    {
                        var offset = 0;
                        while (offset < chunk.Length)
                        {
                            var hit = chunk[offset..].IndexOf(marker);
                            if (hit < 0)
                            {
                                break;
                            }

                            var lineStart = pos + offset + hit + 1;
                            if (!this.TryHandleLineAt(handle, lineStart, length, out _))
                            {
                                // title line still being written: retry from here next time
                                this._scanned = lineStart - 1;
                                this._lastLength = -1;
                                return;
                            }

                            offset += hit + marker.Length;
                        }
                    }

                    if (pos + read >= length)
                    {
                        break;
                    }

                    // keep an overlap so a marker across the chunk border is still found
                    pos += read - Overlap;
                }

                this._scanned = Math.Max(0, length - Overlap);
            }
            finally
            {
                ArrayPool<Byte>.Shared.Return(buffer);
            }
        }

        // Returns false only if a title line at lineStart is not complete yet.
        private Boolean TryHandleLineAt(Microsoft.Win32.SafeHandles.SafeFileHandle handle, Int64 lineStart, Int64 length, out Boolean handled)
        {
            handled = false;
            var size = (Int32)Math.Min(MaxTitleLine, length - lineStart);
            if (size <= 0)
            {
                return true;
            }

            var line = new Byte[size];
            var read = RandomAccess.Read(handle, line, lineStart);
            var span = line.AsSpan(0, read);

            var isCustom = span.StartsWith(CustomMarker);
            if (!isCustom && !span.StartsWith(AiMarker))
            {
                return true;
            }

            var end = span.IndexOf((Byte)'\n');
            if (end < 0)
            {
                // no newline yet: incomplete (or absurdly long) line
                return read == MaxTitleLine;
            }

            try
            {
                using var doc = JsonDocument.Parse(line.AsMemory(0, end));
                var property = isCustom ? "customTitle" : "aiTitle";
                if (doc.RootElement.TryGetProperty(property, out var value) && value.ValueKind == JsonValueKind.String)
                {
                    var title = Normalize(value.GetString());
                    if (title.Length > 0)
                    {
                        if (isCustom)
                        {
                            this._customTitle = title;
                        }
                        else
                        {
                            this._aiTitle = title;
                        }

                        handled = true;
                    }
                }
            }
            catch (JsonException)
            {
            }

            return true;
        }

        // Walks the complete lines at the end of the file backwards until one says
        // whether the turn is running. Metadata lines (attachments, api requests,
        // titles, tools-used, ...) are skipped.
        private static TurnState ReadTurn(Microsoft.Win32.SafeHandles.SafeFileHandle handle, Int64 length)
        {
            var size = (Int32)Math.Min(TurnTailBytes, length);
            if (size <= 0)
            {
                return TurnState.Unknown;
            }

            var buffer = ArrayPool<Byte>.Shared.Rent(size);
            try
            {
                var read = RandomAccess.Read(handle, buffer.AsSpan(0, size), length - size);
                var span = buffer.AsSpan(0, read);
                var end = span.LastIndexOf((Byte)'\n');
                if (end < 0)
                {
                    return TurnState.Unknown;
                }

                span = span[..end];  // drop a line that is still being written
                while (span.Length > 0)
                {
                    var start = span.LastIndexOf((Byte)'\n') + 1;
                    var state = Classify(span[start..]);
                    if (state != TurnState.Unknown)
                    {
                        return state;
                    }

                    if (start == 0)
                    {
                        break;
                    }

                    span = span[..(start - 1)];
                }

                return TurnState.Unknown;
            }
            finally
            {
                ArrayPool<Byte>.Shared.Return(buffer);
            }
        }

        private static TurnState Classify(ReadOnlySpan<Byte> line)
        {
            var type = RootType(line);
            if (type is not ("assistant" or "user" or "system"))
            {
                return TurnState.Unknown;
            }

            if (line.Length > MaxParsedLine)
            {
                // huge tool results / responses only happen mid-turn
                return type == "system" ? TurnState.Unknown : TurnState.Open;
            }

            try
            {
                using var doc = JsonDocument.Parse(line.ToArray());
                var root = doc.RootElement;
                if (type == "system")
                {
                    var subtype = root.TryGetProperty("subtype", out var s) ? s.GetString() : null;
                    return subtype switch
                    {
                        "turn_duration" or "stop_hook_summary" or "away_summary" => TurnState.Ended,
                        "local_command" => TurnState.Command,
                        _ => TurnState.Unknown,
                    };
                }

                if (!root.TryGetProperty("message", out var message) || message.ValueKind != JsonValueKind.Object)
                {
                    return TurnState.Unknown;
                }

                if (type == "assistant")
                {
                    return message.TryGetProperty("stop_reason", out var stop) && stop.ValueKind == JsonValueKind.String
                        && stop.GetString() == "end_turn"
                        ? TurnState.Ended
                        : TurnState.Open;
                }

                var text = "";
                if (message.TryGetProperty("content", out var content))
                {
                    if (content.ValueKind == JsonValueKind.String)
                    {
                        text = content.GetString();
                    }
                    else if (content.ValueKind == JsonValueKind.Array && content.GetArrayLength() > 0
                        && content[0].TryGetProperty("text", out var t) && t.ValueKind == JsonValueKind.String)
                    {
                        text = t.GetString();
                    }
                }

                return text.StartsWith("[Request interrupted", StringComparison.Ordinal)
                    ? TurnState.Interrupted
                    : TurnState.Open;
            }
            catch (JsonException)
            {
                return TurnState.Unknown;
            }
        }

        // The root object's "type" without materialising the (possibly huge) line.
        private static String RootType(ReadOnlySpan<Byte> line)
        {
            try
            {
                var reader = new Utf8JsonReader(line);
                if (!reader.Read() || reader.TokenType != JsonTokenType.StartObject)
                {
                    return null;
                }

                while (reader.Read() && reader.TokenType == JsonTokenType.PropertyName)
                {
                    var isType = reader.ValueTextEquals("type"u8);
                    if (!reader.Read())
                    {
                        return null;
                    }

                    if (isType)
                    {
                        return reader.TokenType == JsonTokenType.String ? reader.GetString() : null;
                    }

                    reader.Skip();
                }
            }
            catch (JsonException)
            {
            }

            return null;
        }

        private static String Normalize(String value) =>
            String.Join(' ', (value ?? "").Split((Char[])null, StringSplitOptions.RemoveEmptyEntries));
    }
}
